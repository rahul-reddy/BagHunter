import {test, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('all stress attempts, hindsight selections, source-bound exports and unavailable results remain visible', async ({page}) => {
  test.setTimeout(60_000);
  await page.goto('/');
  await page.getByRole('button',{name:'Validation Lab',exact:true}).click();
  const panel = page.getByRole('region',{name:'Failure-oriented robustness',exact:true});
  const table = panel.getByRole('table',{name:'All predeclared robustness attempts',exact:true});
  await expect(table.getByRole('row')).toHaveCount(13);
  await expect(panel).toContainText('Hindsight selection:');
  await expect(panel.getByRole('table',{name:'Selected stress exclusion ledger',exact:true})).toContainText('declared security exclusion');
  const selected = panel.getByRole('combobox',{name:'Inspect robustness attempt',exact:true});
  await selected.selectOption('filing_lag_7x_or_168h');
  await expect(panel).toContainText('filing lag 168 hours');
  await selected.selectOption('exclude_declared_micro_bucket');
  await expect(panel).toContainText('This fixture has no members in the declared microcap bucket');
  await selected.selectOption('independent_adjusted_price_series');
  await expect(panel).toContainText('No simulated metrics or executions are substituted for this attempt.');
  await expect(panel.getByRole('table',{name:'Selected stress exclusion ledger',exact:true})).toHaveCount(0);
  const pending = page.waitForEvent('download');
  await panel.getByRole('link',{name:'Download all robustness attempts',exact:true}).click();
  const chunks: Buffer[] = []; for await (const part of (await (await pending).createReadStream())!) chunks.push(Buffer.from(part));
  const report = JSON.parse(Buffer.concat(chunks).toString());
  const run = await (await page.request.get('/api/runs/current')).json();
  expect(report).toEqual(run.validation.robustness);
  expect(report.dataset_sha256).toBe(run.sources[0].sha256);
  expect(report.attempts).toHaveLength(12);
  expect(report.attempts.at(-1).report).toBeNull();
  expect((await page.request.get(`/api/runs/${run.run_id}/reports/robustness.md`)).status()).toBe(200);
  await page.getByRole('combobox',{name:'Ranking sensitivity variant',exact:true}).selectOption('without_price_volume');
  await expect(page.getByText('Removed family: price volume.',{exact:false})).toBeVisible();
  await panel.getByText('Stress definitions and limits',{exact:true}).click();
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
  await page.setViewportSize({width:390,height:844});
  await panel.getByRole('region',{name:'Scrollable robustness attempts',exact:true}).focus();
  await expect(panel.getByRole('region',{name:'Scrollable robustness attempts',exact:true})).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
});

test('a rejected stress never borrows metrics and legacy archives do not invent attempts', async ({page,request}) => {
  const run = await (await request.get('/api/runs/current')).json();
  const payload = structuredClone(run);
  const failed = payload.validation.robustness.attempts.find((row: {id: string}) => row.id === 'wider_cost_2x_or_100bps');
  failed.status = 'REJECTED'; failed.reason = 'POLICY_OR_DATA_BOUNDARY_REJECTED'; failed.report = null;
  await page.route('**/api/runs/current', route => route.fulfill({json:payload}));
  await page.goto('/');
  await page.getByRole('button',{name:'Validation Lab',exact:true}).click();
  const panel = page.getByRole('region',{name:'Failure-oriented robustness',exact:true});
  await panel.getByRole('combobox',{name:'Inspect robustness attempt',exact:true}).selectOption('wider_cost_2x_or_100bps');
  await expect(panel).toContainText('Rejected; no metric fallback');
  await expect(panel).toContainText('No simulated metrics or executions are substituted for this attempt.');
  delete payload.validation.robustness;
  await page.reload();
  await page.getByRole('button',{name:'Validation Lab',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Robustness diagnostics unavailable',exact:true})).toBeVisible();
  await expect(panel).toHaveCount(0);
});
