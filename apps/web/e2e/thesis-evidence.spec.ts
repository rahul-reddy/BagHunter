  await page.getByRole('button',{name:'Add qualitative evidence',exact:true}).click();
  await page.getByText('Risk register coverage',{exact:true}).click();
  const riskTable = page.getByRole('table',{name:'Research risk register coverage',exact:true});
  await expect(riskTable.getByRole('row')).toHaveCount(17);
  await expect(riskTable.getByRole('row').filter({hasText:'Refinancing'})).toContainText('Attributed assertions; not verified');
  await page.getByText('Separately attributed adversarial critique',{exact:true}).click();
  const packet = JSON.parse(await download(page,'Export separate critic request'));
  expect(packet.context.source_context.mode).toBe('FIXTURE');
  expect(packet.context.scenarios).toHaveLength(3);
  expect(packet.request_digest).toBe(await requestDigest(packet.context));
  const review = {schema:'research-critic-v1',request_digest:packet.request_digest,reviewer:'Separate fixture critic',reviewer_kind:'HUMAN',counterargument:'Fictional exercise; this is not empirical thesis evidence.',evidence_gaps:'Real identity and history remain unavailable.',falsification:'Missing verified operating evidence.',citations:[{url:'https://www.sec.gov/Archives/fixture.htm',published_at:'2021-01-01T00:00:00Z'}]};
  await page.getByLabel('Separate critic response JSON',{exact:true}).fill(JSON.stringify(review));
  await page.getByRole('button',{name:'Attach separately attributed critic',exact:true}).click();
  await expect(page.getByText('Review matches this packet; independence remains unverified',{exact:true})).toBeVisible();
  await page.getByLabel('Catalyst date',{exact:true}).fill('2026-10-28');
  await page.getByLabel('Catalyst title',{exact:true}).fill('Acceptance-only planned research event');
  await page.getByRole('button',{name:'Add catalyst event',exact:true}).click();
  await expect(page.getByText('Critic review is stale; the research packet changed',{exact:true})).toBeVisible();
  const dossier = JSON.parse(await download(page,'Download thesis dossier'));
  expect(dossier.critic_status).toBe('STALE_REQUEST');expect(dossier.catalyst_calendar).toHaveLength(1);
  expect(dossier.source_context).toEqual(packet.context.source_context);
  expect(dossier.verified_real_theses).toBe(0);expect(dossier.risk_register.find((row: {topic:string}) => row.topic === 'Refinancing').records).toBe(1);
  await page.getByRole('button',{name:'Save draft locally',exact:true}).click();
  await page.getByLabel('Research hypothesis',{exact:true}).fill('Changed after save');
  await page.getByRole('button',{name:'Load saved draft',exact:true}).click();
  await expect(page.getByLabel('Research hypothesis',{exact:true})).toHaveValue('');
  await expect(page.getByRole('button',{name:'Download thesis memo',exact:true})).toBeEnabled();
  const memo = await download(page,'Download thesis memo');
  expect(memo).toContain('Separate fixture critic');expect(memo).toContain('STALE_REQUEST');expect(memo).toContain('Acceptance-only planned research event');
  await page.reload();await page.getByRole('button',{name:'Thesis Studio',exact:true}).click();
