  await expect(page.getByRole('button',{name:'Download thesis dossier',exact:true})).toBeEnabled();
  const reloaded = JSON.parse(await download(page,'Download thesis dossier'));
  expect(reloaded.catalyst_calendar).toEqual(dossier.catalyst_calendar);
