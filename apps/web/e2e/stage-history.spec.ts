import {test, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('complete dated stage history paginates, cites inputs and exports without truncation', async ({page}) => {
  await page.goto('/');
  await page.getByRole('button', {name: 'BagHunter Radar', exact: true}).click();
  await page.getByRole('button', {name: 'DEMO-A fx-compound', exact: true}).click();
  const panel = page.getByRole('region', {name: 'Stage history explorer', exact: true});
  await expect(panel).toContainText('FULL_KNOWABLE_HISTORY');
  const table = panel.getByRole('table', {name: 'Dated discovery stage history', exact: true});
  await expect(table.getByRole('row')).toHaveCount(21);
  const latest = await table.getByRole('row').nth(1).textContent();
  await panel.getByRole('button', {name: 'Older history observations', exact: true}).click();
  await expect(panel).toContainText('History observations 21–40');
  expect(await table.getByRole('row').nth(1).textContent()).not.toBe(latest);
  await panel.getByRole('button', {name: 'Newer history observations', exact: true}).click();
  await table.locator('summary').first().click();
  await expect(table).toContainText('Evaluated original trigger:');
  const link = table.getByRole('link').first();
  await expect(link).toBeVisible();
  await expect(link).toHaveAttribute('href', 'fixture://fixture-v1');
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
  const pending = page.waitForEvent('download');
  await panel.getByRole('button', {name: 'Export complete instrument history', exact: true}).click();
  const stream = await (await pending).createReadStream(); const parts: Buffer[] = [];
  for await (const chunk of stream!) parts.push(Buffer.from(chunk));
  const output = JSON.parse(Buffer.concat(parts).toString());
  expect(output.history_scope).toBe('FULL_KNOWABLE_HISTORY');
  expect(output.rows.length).toBeGreaterThan(21);
  expect(output.rows.every((row: {asof: string}) => Date.parse(row.asof) <= Date.parse(output.asof))).toBe(true);
  await page.setViewportSize({width: 390, height: 844});
  await panel.getByRole('region', {name: 'Scrollable stage history', exact: true}).focus();
  await expect(panel.getByRole('region', {name: 'Scrollable stage history', exact: true})).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
});

test('expired instrument history and legacy windows retain explicit scope and missing prices', async ({page, request}) => {
  const response = await request.get('/api/runs/current');
  const run = await response.json();
  const row = {asof: run.asof, session: run.asof.slice(0, 10), stage: 'INVALIDATED', previous_stage: 'WATCH', reason: 'Instrument no longer eligible at this clock', close: null, score: null};
  const payload = structuredClone(run);
  payload.discovery.history['fx-archived'] = [row];
  await page.route('**/api/runs/current', route => route.fulfill({json: payload}));
  await page.goto('/');
  await page.getByRole('button', {name: 'BagHunter Radar', exact: true}).click();
  await page.getByRole('button', {name: 'DEMO-A fx-compound', exact: true}).click();
  const panel = page.getByRole('region', {name: 'Stage history explorer', exact: true});
  await panel.getByLabel('Stage history instrument', {exact: true}).selectOption('fx-archived');
  await expect(panel).toContainText('Instrument no longer eligible at this clock');
  await expect(panel.getByRole('cell', {name: 'Unavailable', exact: true})).toHaveCount(2);
  delete payload.discovery.history;
  delete payload.discovery.history_scope;
  for (const signal of payload.signals) signal.stage_history = signal.stage_history.slice(-21);
  await page.reload();
  await page.getByRole('button', {name: 'BagHunter Radar', exact: true}).click();
  await page.getByRole('button', {name: 'DEMO-A fx-compound', exact: true}).click();
  await expect(panel).toContainText('Legacy archived history · 21 dated observations');
  await expect(panel.getByLabel('Stage history instrument', {exact: true})).toHaveCount(0);
});
